create or replace function public.start_game(input_game_id text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  new_play_id uuid;
begin
  if current_user_id is null then raise exception '로그인이 필요합니다.'; end if;
  if not exists (select 1 from public.game_definitions where id = input_game_id and is_active) then
    raise exception '플레이할 수 없는 게임입니다.';
  end if;
  insert into public.game_plays (user_id, game_id)
  values (current_user_id, input_game_id)
  returning id into new_play_id;
  return new_play_id;
end;
$$;

create or replace function public.finish_game(
  input_play_id uuid,
  input_score integer,
  input_success boolean
)
returns table (
  play_id uuid,
  rewarded_ticket_type text,
  rewarded_quantity integer,
  normal_balance integer,
  premium_balance integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  target_play public.game_plays%rowtype;
  selected_ticket_type text;
  elapsed_seconds integer;
begin
  if auth.uid() is null then raise exception '로그인이 필요합니다.'; end if;
  if input_score not between 0 and 100 then raise exception '점수는 0부터 100까지 입력할 수 있습니다.'; end if;

  select * into target_play from public.game_plays where id = input_play_id for update;
  if target_play.id is null then raise exception '게임 기록을 찾을 수 없습니다.'; end if;
  if target_play.user_id <> auth.uid() then raise exception '본인의 게임만 완료할 수 있습니다.'; end if;

  if target_play.status = 'in_progress' then
    elapsed_seconds := greatest(0, floor(extract(epoch from (now() - target_play.started_at)))::integer);
    update public.game_plays set
      score = input_score,
      success = input_success,
      play_time_seconds = elapsed_seconds,
      played_at = now(),
      status = 'completed'
    where id = input_play_id;

    select rule.ticket_type into selected_ticket_type
    from public.game_reward_rules rule
    where rule.is_active
      and input_score >= rule.min_score
      and (not rule.requires_success or input_success)
    order by rule.priority desc
    limit 1;

    if selected_ticket_type is not null then
      insert into public.game_rewards (game_play_id, user_id, ticket_type)
      values (input_play_id, auth.uid(), selected_ticket_type)
      on conflict (game_play_id) do nothing;

      if found then
        insert into public.wish_ticket_balances (user_id, ticket_type, quantity)
        values (auth.uid(), selected_ticket_type, 1)
        on conflict (user_id, ticket_type) do update
        set quantity = public.wish_ticket_balances.quantity + 1, updated_at = now();
      end if;
    end if;
  end if;

  return query
  select
    target_play.id,
    reward.ticket_type,
    coalesce(reward.quantity, 0),
    coalesce((select balance.quantity from public.wish_ticket_balances balance where balance.user_id = auth.uid() and balance.ticket_type = 'normal'), 0),
    coalesce((select balance.quantity from public.wish_ticket_balances balance where balance.user_id = auth.uid() and balance.ticket_type = 'premium'), 0)
  from (select 1) seed
  left join public.game_rewards reward on reward.game_play_id = target_play.id;
end;
$$;

revoke all on function public.start_game(text) from public;
revoke all on function public.finish_game(uuid, integer, boolean) from public;
grant execute on function public.start_game(text) to authenticated;
grant execute on function public.finish_game(uuid, integer, boolean) to authenticated;
grant select on public.game_definitions, public.game_reward_rules, public.game_plays, public.game_rewards to authenticated;
