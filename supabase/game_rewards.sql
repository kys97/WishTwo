create table if not exists public.game_definitions (
  id text primary key,
  category text not null check (category in ('ten-seconds', 'one-minute', 'full-match')),
  name text not null,
  is_active boolean not null default true
);

create table if not exists public.game_reward_rules (
  id bigint generated by default as identity primary key,
  ticket_type text not null check (ticket_type in ('normal', 'premium')),
  min_score integer not null check (min_score between 0 and 100),
  requires_success boolean not null default true,
  priority integer not null default 0,
  is_active boolean not null default true,
  unique (ticket_type)
);

create table if not exists public.game_plays (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  game_id text not null references public.game_definitions(id),
  score integer check (score between 0 and 100),
  success boolean,
  play_time_seconds integer check (play_time_seconds >= 0),
  started_at timestamptz not null default now(),
  played_at timestamptz,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed'))
);

create table if not exists public.game_rewards (
  id uuid primary key default gen_random_uuid(),
  game_play_id uuid not null unique references public.game_plays(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  ticket_type text not null check (ticket_type in ('normal', 'premium')),
  quantity integer not null default 1 check (quantity = 1),
  awarded_at timestamptz not null default now()
);

create index if not exists game_plays_user_played_idx on public.game_plays(user_id, played_at desc);
create index if not exists game_rewards_user_awarded_idx on public.game_rewards(user_id, awarded_at desc);

